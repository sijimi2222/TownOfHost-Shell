    internal static string Key(CustomRoles role)
        => Normalize(Readings.TryGetValue(role.ToString(), out var reading)
            ? reading : Translator.GetRoleString(role.ToString()));

    internal static string Normalize(string text)
    {
        text = Regex.Replace(text ?? "", "<[^>]*>", "").Normalize(NormalizationForm.FormKC)
            .ToLowerInvariant().Normalize(NormalizationForm.FormD);
        const string small = "ぁぃぅぇぉっゃゅょゎ";
        const string large = "あいうえおつやゆよわ";
        var result = new StringBuilder(text.Length);
        foreach (char original in text)
        {
            if (char.GetUnicodeCategory(original) == UnicodeCategory.NonSpacingMark
                || char.IsWhiteSpace(original) || original == 'ー') continue;
            char c = original is >= '\u30a1' and <= '\u30f6' ? (char)(original - 0x60) : original;
            int index = small.IndexOf(c);
            result.Append(index >= 0 ? large[index] : c);
        }
        return result.ToString();
    }
